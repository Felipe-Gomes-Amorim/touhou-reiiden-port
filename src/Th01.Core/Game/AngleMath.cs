    public static int Sin8(int angle) => SinTable[angle & 0xFF];
    public static int Cos8(int angle) => SinTable[(angle & 0xFF) + 64];

    /// <summary>polar_x: ((long)radius * Cos8(angle)) >> 8 (arithmetic shift, so negatives round away from zero) + center.</summary>
    public static int PolarX(int center, int radius, int angle) => (int)(((long)radius * Cos8(angle)) >> 8) + center;
    public static int PolarY(int center, int radius, int angle) => (int)(((long)radius * Sin8(angle)) >> 8) + center;

    /// <summary>iatan2(y, x): 0..255, 256 steps per turn, y pointing down. (0,0) gives 0.</summary>
    public static int Iatan2(int y, int x)
    {
        if ((y | x) == 0) return 0;
        int ay = Math.Abs(y), ax = Math.Abs(x);
        int a;
        if (ax == ay) a = 32;
        else if (ax > ay) a = AtanTable[(ay << 8) / ax];
        else a = 64 - AtanTable[(ax << 8) / ay];
        if (x < 0) a = 128 - a;
        if (y < 0) a = -a;
        return a & 0xFF;
    }
